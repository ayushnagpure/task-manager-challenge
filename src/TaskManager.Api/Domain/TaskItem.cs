namespace TaskManager.Api.Domain;

/// <summary>
/// A task. Persistence entity; never exposed directly by the API (DTOs are used instead).
/// Named <c>TaskItem</c> to avoid clashing with <see cref="System.Threading.Tasks.Task"/>; the table is <c>Tasks</c>.
/// </summary>
public class TaskItem
{
    /// <summary>Database identity.</summary>
    public int Id { get; set; }

    /// <summary>Short title (required, max 200 characters).</summary>
    public string Title { get; set; } = string.Empty;

    /// <summary>Optional longer description (max 2000 characters).</summary>
    public string? Description { get; set; }

    /// <summary>Workflow state.</summary>
    public TaskItemStatus Status { get; set; }

    /// <summary>Importance.</summary>
    public TaskPriority Priority { get; set; }

    /// <summary>Optional name of the person the task is assigned to (max 100 characters).</summary>
    public string? AssignedTo { get; set; }

    /// <summary>When the task was created (UTC).</summary>
    public DateTimeOffset CreatedDate { get; set; }

    /// <summary>When the task was last changed (UTC).</summary>
    public DateTimeOffset ModifiedDate { get; set; }

    /// <summary>Soft-delete flag. Deleted tasks are hidden by a global query filter.</summary>
    public bool IsDeleted { get; set; }

    /// <summary>SQL Server rowversion used for optimistic concurrency. Generated by the database.</summary>
    public byte[] RowVersion { get; set; } = [];
}
